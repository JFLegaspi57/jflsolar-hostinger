    <section aria-labelledby="who">
        <h2 id="who">Who is AE Solar?</h2>
        <p>AE Solar, now branded <strong>AESOLAR</strong>, is a German solar panel company. It was founded in 2003 in Königsbrunn, Bavaria, as a family-run installation business by Dr. Alexander Maier and his brothers. Its headquarters are now in Gersthofen, near Augsburg.</p>
        <p>The company designs its panels in Germany and builds them in its own factories in China (Huai’an, Jiangsu) and Turkey (Manisa). It sells in over 100 countries.</p>
