    <section aria-labelledby="shade">
        <h2 id="shade">Shade and bypass diodes, explained</h2>
        <p>The cells in a panel are connected in series, like old Christmas lights: a shaded cell can hold back all the others and even heat up (a “hot spot”). <strong>Bypass diodes</strong> let current flow around a shaded section so the rest of the panel keeps working.</p>
        <p>Most panels, including the Meteor 630 W we carry, have three bypass diodes, each covering a third of the panel. AE Solar became known for going further: since 2016 it has developed panels with many more bypass paths, and its 2026 <strong>ShadeStar</strong> panel splits the cells into small groups with flat diodes built into the panel, so a leaf, a pole shadow or a vent pipe costs far less power. ShadeStar is a separate product for heavily shaded roofs; for an unshaded roof, a standard panel like the Meteor gives more power per peso.</p>
    </section>

