        <h2 id="who">Who is Seraphim?</h2>
        <p>Seraphim Energy Group is a Chinese solar panel manufacturer founded in 2011 and headquartered in Changzhou, Jiangsu province. It is a private company, led by chairman Polaris Li.</p>
        <p>Seraphim is smaller than giants such as JinkoSolar, but it focuses on export markets and large solar farms, and it has repeatedly done well in independent reliability testing.</p>
