    <section aria-labelledby="tested">
        <h2 id="tested">Independently tested</h2>
        <p>Every manufacturer says its panels are durable. <strong>Kiwa PVEL</strong>, an independent US test lab, checks that claim: it buys panels and puts them through accelerated aging, including repeated hot-cold cycles, damp heat, simulated hail and mechanical stress, then measures how much power they lose. Panels that lose the least are named “Top Performers” in its yearly Scorecard.</p>
        <p>Seraphim has been a Top Performer six times, most recently in 2025 for its Sable TOPCon panels. For you, that means better evidence that the panel will keep its output over decades on a hot, humid, typhoon-exposed roof.</p>
    </section>

    <section aria-labelledby="philippines">
        <h2 id="philippines">Seraphim in the Philippines</h2>
        <ul class="dots">
            <li>Seraphim entered the Philippine market in <strong>2016</strong>.</li>
            <li>In <strong>2020</strong> it agreed to supply 183 MW of panels to ERS Energy for solar farms in Alaminos, Laguna, and in Zambales.</li>
            <li>In <strong>2022</strong> it shipped 72 MW to Citicore Power, bringing its deliveries to the Philippines to over 200 MW in two years.</li>
            <li>In <strong>2023</strong> it was chosen to supply 300 MW for a ground-mounted solar plant in Zambales.</li>
        </ul>
        <p class="mt-3">These are utility-scale projects, where buyers test panels closely before ordering hundreds of thousands of them.</p>
    </section>

