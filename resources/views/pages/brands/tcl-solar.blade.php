    <section aria-labelledby="who">
        <h2 id="who">Who is TCL Solar?</h2>
        <p>TCL Solar is the solar panel brand of TCL Zhonghuan (TZE), the solar manufacturing company of TCL Technology, the Chinese group many Filipinos know from TVs and appliances. TCL entered solar in 2020 by buying the Zhonghuan group in Tianjin, China, whose roots go back to 1958 and which was already one of the world’s biggest makers of silicon wafers, the thin slices every solar cell is made from.</p>
        <p>From wafers it moved into cells and panels. It also took control of Maxeon, the company behind SunPower panels outside the United States, so today it sells two panel brands: TCL Solar and SunPower.</p>
        <dl class="ba-facts mt-6">
