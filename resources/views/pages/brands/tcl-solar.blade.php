    <section aria-labelledby="makes">
        <h2 id="makes">What TCL Solar makes</h2>
        <div class="ba-family">
            <h3>N-type TOPCon panels</h3>
            <p>Bifacial, glass-glass panels for homes, businesses and solar farms, including both series we carry. Many use TCL’s own large G12 wafers.</p>
        </div>
        <div class="ba-family">
            <h3>Shingled panels</h3>
            <p>Cells cut into strips and overlapped like roof shingles, with no gaps between them, so more of the panel’s surface makes power. Our 700–725 W panel is one of these.</p>
        </div>
        <div class="ba-family">
            <h3>Back-contact (BC) panels and storage</h3>
            <p>High-efficiency back-contact panels (all wiring on the back of the cell) under the TCL Solar and SunPower brands, plus home and commercial battery storage.</p>
        </div>
    </section>

    <section aria-labelledby="tested">
        <h2 id="tested">Tier 1 and backing</h2>
        <ul class="dots">
            <li><strong>Tier 1:</strong> TCL Solar is on BloombergNEF’s Tier 1 list of panel makers (Q3 2025 and again Q1 2026). This list measures bankability: banks finance big solar projects that use these panels.</li>
            <li><strong>Makes its own wafers:</strong> owning the first step of the chain means steady supply and close control of the silicon quality in every cell.</li>
            <li><strong>Big parent company:</strong> TCL Technology is a large, listed electronics group, which matters for a 30-year power warranty.</li>
        </ul>
        <p class="mt-3">For you, this means a large, well-funded manufacturer that is likely to be around for the full warranty period.</p>
    </section>

