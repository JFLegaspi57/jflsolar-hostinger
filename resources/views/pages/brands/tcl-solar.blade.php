        <h3 class="mt-6">What this means for you</h3>
        <ul class="dots">
            <li><strong>N-type TOPCon:</strong> more output per panel, slower aging and better performance in heat and low light than older PERC panels.</li>
            <li><strong>Bifacial, dual glass:</strong> the back side adds power from reflected light (about 80% as strong as the front), and glass on both sides protects the cells from moisture.</li>
            <li><strong>Shingled 725 W:</strong> fewer panels for the same kW, so less mounting and wiring per kW. But it is wider (1303 mm) and heavier (38.4 kg) than a 620 W panel: it needs its own rail layout, clamps placed where TCL’s manual specifies, and two to three people to lift.</li>
            <li><strong>Higher current:</strong> the 725 W panel makes about 18 A (more with rear-side gain), so the inverter’s input current limit per MPPT matters. We check this and work out the string sizes for your inverter.</li>
        </ul>
