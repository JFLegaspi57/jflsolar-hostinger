    <section aria-labelledby="who">
        <h2 id="who">Who is Solis?</h2>
        <p>Solis is the inverter brand of <strong>Ginlong Technologies</strong>, founded in 2005 in Ningbo, Zhejiang province, China, by Wang Yiming, who still leads the company as chairman and CEO. It has been listed on the Shenzhen Stock Exchange since 2019 (code 300763).</p>
        <p>Solis focuses on string inverters, the type used on homes, businesses and many solar farms, and has become one of the three biggest inverter makers in the world.</p>
