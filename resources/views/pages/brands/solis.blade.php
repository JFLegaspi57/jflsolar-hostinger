    <section aria-labelledby="makes">
        <h2 id="makes">What Solis makes</h2>
        <div class="ba-family">
            <h3>Hybrid inverters</h3>
            <p>Single-phase low-voltage hybrids for 48 V batteries, from 3 to 10 kW (S6-EH1P L-PLUS) and 12 to 18 kW (S6-EH1P K03 series); three-phase low-voltage hybrids; high-voltage hybrids; and commercial hybrids up to 125 kW.</p>
        </div>
        <div class="ba-family">
            <h3>Grid-tie inverters</h3>
            <p>Residential single- and three-phase models, commercial inverters around 50 kW, and utility inverters up to 350 kW.</p>
        </div>
        <div class="ba-family">
            <h3>Off-grid inverters and batteries</h3>
            <p>Off-grid inverters for 48 V batteries, and since March 2026 its own SolisStorage home batteries.</p>
        </div>
        <div class="ba-family">
            <h3>Monitoring</h3>
            <p>The <strong>SolisCloud</strong> app and platform, including an AI feature (2025) that plans battery charging around electricity prices and weather forecasts.</p>
        </div>
    </section>

    <section aria-labelledby="features">
        <h2 id="features">Features in plain words</h2>
        <ul class="dots">
            <li><strong>Generator integration (“Solarator”).</strong> Solis hybrids launched in the Philippines in 2025 work with a generator for round-the-clock backup.</li>
            <li><strong>Surge power.</strong> Up to 200% of rating for 10 seconds, to start motors such as aircon compressors and water pumps.</li>
            <li><strong>AC coupling.</strong> A Solis hybrid can work alongside an existing grid-tie system to add a battery.</li>
            <li><strong>Arc-fault protection (AFCI).</strong> Detects dangerous arcing in the DC wiring and shuts down, reducing fire risk.</li>
            <li><strong>IP66.</strong> Dust-tight and protected against strong water jets.</li>
        </ul>
    </section>

