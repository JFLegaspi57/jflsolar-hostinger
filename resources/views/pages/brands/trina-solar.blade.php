    <section aria-labelledby="tested">
        <h2 id="tested">Trusted and tested</h2>
        <ul class="dots">
            <li><strong>Bankable:</strong> in BloombergNEF’s bankability survey, Trinasolar has been rated 100% bankable by all respondents eight times. Banks and investors are comfortable financing projects that use its panels.</li>
            <li><strong>Independently tested:</strong> <strong>Kiwa PVEL</strong>, an independent US test lab, buys panels and puts them through accelerated aging (hot-cold cycles, damp heat, simulated hail and mechanical stress). Trinasolar has been a Top Performer for 11 years in a row.</li>
            <li><strong>Research:</strong> it has set 26 world records for solar cell efficiency and module power.</li>
        </ul>
        <p class="mt-3">For you, this means a panel maker that is likely to be around for the full 30-year warranty, with panels that have proven themselves in tough testing.</p>
    </section>

    <section aria-labelledby="philippines">
        <h2 id="philippines">Trinasolar in the Philippines</h2>
        <ul class="dots">
            <li>Trinasolar entered the Philippine market in <strong>2013</strong>.</li>
            <li>It has worked with <strong>PetroGreen Energy</strong> since 2015 on solar farms such as Tarlac-2 (20 MWp), Dagohoy in Bohol (27 MWp) and Limbauan in Isabela (40 MWp, 52,000 Vertex N panels).</li>
            <li>In <strong>2024</strong> it signed a <strong>2 GW</strong> supply deal with Citicore Renewable Energy, the largest of its kind in the Philippines.</li>
            <li>In <strong>2026</strong> its Vertex N panels powered the 25 MWp Bugallon solar plant in Pangasinan, which started selling power to the Luzon grid in September.</li>
        </ul>
        <p class="mt-3">These utility-scale projects run in the same heat, humidity and typhoons that your roof faces.</p>
    </section>

