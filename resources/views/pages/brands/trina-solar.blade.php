    <section aria-labelledby="who">
        <h2 id="who">Who is Trinasolar?</h2>
        <p>Trina Solar (now written Trinasolar) is one of the oldest and largest solar companies in the world. Gao Jifan founded it in 1997 in Changzhou, Jiangsu province, China, where its global headquarters still is. In 2022 it opened an international headquarters in Shanghai, and its shares trade on Shanghai’s STAR Market.</p>
        <p>Besides solar panels, Trinasolar makes large battery storage systems (Trina Storage) and offers complete systems and services for solar plants.</p>
